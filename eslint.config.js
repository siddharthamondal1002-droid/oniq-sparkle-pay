/**
 * Why the project fences below each have their own rule id instead of all
 * being `no-restricted-syntax`.
 *
 * ESLint flat config REPLACES a rule's options when a later config object sets
 * the same rule id — it does not merge them. Four blocks below previously all
 * set `no-restricted-syntax`, so for any given file only the last matching
 * block survived. Verified with `--print-config`: on
 * src/routes/_authenticated/app.index.tsx the effective rule was the single
 * warn-level hardcoded-string selector, and the media-URL, currency and RTL
 * fences were silently inert across every .tsx under src/routes and
 * src/components. A probe file calling createSignedUrl() and getPublicUrl()
 * with `className="ml-2 text-left"` and a literal ₹ produced zero findings.
 *
 * Distinct rule ids are independent, so each block's own `files` / `ignores`
 * apply exactly as written.
 */
function selectorFence(entries) {
  return {
    meta: { type: "problem", schema: [] },
    create(context) {
      const visitors = {};
      for (const { selector, message } of entries) {
        visitors[selector] = (node) => context.report({ node, message });
      }
      return visitors;
    },
  };
}

