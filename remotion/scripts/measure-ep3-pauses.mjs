// Find the pauses in Episode 3's narration and print them as a TS table.
//
//   cd remotion && node scripts/measure-ep3-pauses.mjs > src/ep3/pauses.ts
//
// WHY THIS EXISTS. `allocateFrames` divides a scene between its shots by
// weight, and weight knows nothing about where the sentences are. Measured
// against this episode's own narration, only 11 of 44 interior cuts landed
// within 150ms of a pause and 20 of 44 were more than 0.6s from any pause — the
// worst being the episode's opening cut, 2.18s adrift. A cut in the middle of a
// clause makes the new image arrive detached from the words that introduced it,
// and that reads as the picture lagging the voice. It is not sync drift; the
// frames are exact.
//
// `snapCutsToPauses` fixes it, but it needs to know where the pauses ARE, and
// the composition runs in a browser bundle that cannot open an mp3. So the
// pauses are measured once, here, and committed as data — exactly like the
// scene durations in manifest.ts, and for the same reason: the thing derived
// from audio has to be reviewable by a person and identical on every machine.
//
// RE-RUN THIS AFTER ANY CHANGE TO THE NARRATION. A stale pause table snaps cuts
// onto silence that has moved, which is worse than not snapping at all.
//
// HOW A PAUSE IS DETECTED. A 20ms RMS envelope, and any run of at least 220ms
// below -40 dBFS. The floor sits well clear of both ends: narration measures
// around -28 dBFS RMS and the gaps measure near the noise floor, so nothing
// lands near the line. 220ms is long enough to exclude the stop before a
// plosive and short enough to catch a comma.
import { execFileSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { findBin } from './findFfmpeg.mjs';
import { EPISODE, PUBLIC_DIR, sceneIds } from './episode.mjs';

const PUBLIC = PUBLIC_DIR;
const SR = 16000;
const FPS = 30;
const WINDOW = 0.02;
const FLOOR_DB = -40;
const MIN_PAUSE = 0.22;

/** 20ms RMS envelope of one mp3, in dBFS. */
function envelope(ffmpeg, file) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pause-'));
  const wav = path.join(dir, 'a.wav');
  try {
    execFileSync(ffmpeg, [
      '-nostdin', '-v', 'error', '-i', file,
      '-ac', '1', '-ar', String(SR), '-c:a', 'pcm_s16le', '-f', 'wav', '-y', wav,
    ]);
    const b = fs.readFileSync(wav);
    // A real chunk walk, not a fixed 44-byte skip: ffmpeg writes a LIST/INFO
    // chunk before `data` often enough that assuming 44 measures metadata as
    // audio and reports a pause that is not there.
    let off = -1;
    let len = 0;
    for (let i = 12; i + 8 <= b.length; ) {
      const id = b.toString('ascii', i, i + 4);
      const size = b.readUInt32LE(i + 4);
      if (id === 'data') {
        off = i + 8;
        len = Math.min(size, b.length - off);
        break;
      }
      i += 8 + size + (size % 2);
    }
    if (off < 0) throw new Error(`${file}: no data chunk in the decoded wav`);

    const step = Math.round(SR * WINDOW);
    const out = [];
    for (let s = 0; (s + step) * 2 <= len; s += step) {
      let sum = 0;
      for (let k = 0; k < step; k++) {
        const v = b.readInt16LE(off + (s + k) * 2) / 32768;
        sum += v * v;
      }
      out.push(20 * Math.log10(Math.sqrt(sum / step) + 1e-12));
    }
    return out;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * Pause CENTRES, in frames from the start of the scene.
 *
 * The centre rather than the start, because a cut wants to sit in the middle of
 * the silence: land on its leading edge and you clip the outgoing word's decay,
 * land on the trailing edge and the incoming word starts on the old picture.
 */
function pauseFrames(env) {
  const out = [];
  let run = 0;
  for (let i = 0; i <= env.length; i++) {
    if (i < env.length && env[i] < FLOOR_DB) {
      run += 1;
      continue;
    }
    if (run * WINDOW >= MIN_PAUSE) {
      const midSeconds = (i - run / 2) * WINDOW;
      out.push(Math.round(midSeconds * FPS));
    }
    run = 0;
  }
  return out;
}

const ffmpeg = findBin('ffmpeg');
const scenes = sceneIds();
const missing = scenes.filter((id) => !fs.existsSync(path.join(PUBLIC, `${id}.mp3`)));
if (missing.length > 0) throw new Error(`missing narration: ${missing.join(', ')}`);

const rows = scenes.map((id) => {
  const frames = pauseFrames(envelope(ffmpeg, path.join(PUBLIC, `${id}.mp3`)));
  // A scene with no interior pause cannot be snapped, and that is worth seeing
  // in the output rather than discovering as a cut that never moves.
  return { id, frames };
});

console.log(`// GENERATED by scripts/measure-ep3-pauses.mjs — do not hand-edit.`);
console.log(`//`);
console.log(`// Pause centres in each scene's narration, in FRAMES at ${FPS}fps from the`);
console.log(`// scene's own start. A pause is >=${MIN_PAUSE * 1000}ms below ${FLOOR_DB} dBFS on a`);
console.log(`// ${WINDOW * 1000}ms RMS envelope. Re-run after ANY change to the narration mp3s.`);
console.log(``);
console.log(`export const ${EPISODE.toUpperCase()}_PAUSES: Record<string, number[]> = {`);
for (const r of rows) console.log(`  ${r.id}: [${r.frames.join(', ')}],`);
console.log(`};`);
console.log(``);
const totals = rows.reduce((a, r) => a + r.frames.length, 0);
console.log(`// ${totals} pauses across ${rows.length} scenes.`);
for (const r of rows) {
  if (r.frames.length === 0) console.log(`// WARNING: ${r.id} has no detectable pause.`);
}
