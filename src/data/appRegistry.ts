// ONIQ app registry — the single source of truth for every third-party app
// tile. Pure data + pure helpers; no React, no side effects.
//
// Enforcement lives in code, not convention:
//  - verified:false  → effectiveLaunchType() returns "webOnly" (a wrong
//    package id that fails silently is worse than a web link that works)
//  - status !== "active" → visibleApps() never returns it (rows kept for
//    history — e.g. JioCinema/Hotstar merged into JioHotstar)
//  - countries mismatch → never rendered for the active country
//
// HARD CONTENT RULE: no dating / hookup / romantic-discovery apps, ever.
// The registry test suite enforces this against a blocklist.

export type Country = "IN" | "US" | "GB" | "AE" | "CA" | "AU" | "SG";

export type CategoryId =
  | "food"
  | "rides"
  | "quickcommerce"
  | "services"
  | "payments"
  | "social"
  | "shopping"
  | "beauty"
  | "fashion"
  | "entertainment";

export type AppEntry = {
  id: string;
  name: string; // brand name — NEVER translated, Latin script in all locales
  tagline: string;
  category: CategoryId;
  countries: Country[] | "*";
  packageId?: string; // Android launch key
  iosAppId?: string;
  scheme?: string; // e.g. "phonepe://"
  webUrl: string; // always present — the final fallback
  launchType: "package" | "scheme" | "universalLink" | "webOnly";
  verified: boolean; // false => force webOnly at runtime
  status: "active" | "rebranded" | "merged" | "shutdown" | "withdrawn";
  replacedBy?: string; // id of successor when status !== "active"
  hidden?: boolean; // present in data but never rendered (e.g. Pay-by-UPI shortcut)
  color: string;
  letter: string;
  emoji?: string;
};

export type TileLabel = {
  label: string; // international English — the default
  labelHi: string; // Hindi (Devanagari)
  labelByCountry?: Partial<Record<Country, string>>;
};

