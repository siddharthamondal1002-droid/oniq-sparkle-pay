/** True when `entry` is offered in `country`. */
export function appAvailableIn(entry: Pick<AppEntry, "countries">, country: Country): boolean {
  return entry.countries === "*" || entry.countries.includes(country);
}

/** verified:false must NEVER attempt a native launch. */
export function effectiveLaunchType(
  entry: Pick<AppEntry, "launchType" | "verified">,
): AppEntry["launchType"] {
  return entry.verified ? entry.launchType : "webOnly";
}

/** The only entries any surface may render for a country. */
export function visibleApps(country: Country, category?: CategoryId): AppEntry[] {
  return APP_REGISTRY.filter(
    (a) =>
      a.status === "active" &&
      !a.hidden &&
      appAvailableIn(a, country) &&
      (category === undefined || a.category === category),
  );
}

/** Android <queries> package list — generated from the registry so the
 *  manifest can never drift (guarded by the registry test suite). */
export function queryPackageIds(): string[] {
  const ids = APP_REGISTRY.filter(
    (a) => a.status === "active" && a.verified && a.launchType === "package" && a.packageId,
  ).map((a) => a.packageId!);
  ids.push("com.android.vending"); // Play Store tier of the launch fallback
  return Array.from(new Set(ids)).sort();
}
