export const HEALTH_STRINGS: Record<"en" | "hi" | "bn", Dict> = { en, hi, bn };

let registered = false;

/** Idempotent; the health layout route calls it once on import. */
export function registerHealthTranslations(): void {
  if (registered) return;
  registered = true;
  for (const lang of Object.keys(HEALTH_STRINGS) as Array<keyof typeof HEALTH_STRINGS>) {
    registerTranslations(lang, HEALTH_STRINGS[lang]);
  }
}

/** Fill `{date}`-style placeholders. */
export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) =>
    Object.prototype.hasOwnProperty.call(values, k) ? values[k] : m,
  );
}
